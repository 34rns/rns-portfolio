import { sql } from "drizzle-orm";
import {
  boolean,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";

export const projectStatus = pgEnum("project_status", ["draft", "published"]);
export const projectPlacement = pgEnum("project_placement", ["featured", "unlisted"]);
export const userRole = pgEnum("user_role", ["admin", "customer"]);
export const purchaseStatus = pgEnum("purchase_status", [
  "pending",
  "paid",
  "failed",
  "refunded",
]);

export type ThemeOptions = {
  accent?: string;
  modelUrl?: string;
  lighting?: string;
  [key: string]: unknown;
};

export const users = pgTable("users", {
  id: uuid("id").primaryKey().defaultRandom(),
  email: text("email").notNull().unique(),
  name: text("name"),
  passwordHash: text("password_hash"),
  role: userRole("role").notNull().default("customer"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const projects = pgTable("projects", {
  id: uuid("id").primaryKey().defaultRandom(),
  slug: text("slug").notNull().unique(),
  title: text("title").notNull(),
  tagline: text("tagline").notNull(),
  description: text("description").notNull(),
  coverImageUrl: text("cover_image_url"),
  gallery: jsonb("gallery").$type<string[]>().notNull().default(sql`'[]'::jsonb`),
  tags: text("tags").array().notNull().default(sql`'{}'::text[]`),
  liveUrl: text("live_url"),
  repoUrl: text("repo_url"),
  year: integer("year").notNull(),
  status: projectStatus("status").notNull().default("draft"),
  placement: projectPlacement("placement").notNull().default("featured"),
  sortOrder: integer("sort_order").notNull().default(0),
  theme: text("theme").notNull().default("professional"),
  themeOptions: jsonb("theme_options").$type<ThemeOptions>().notNull().default(sql`'{}'::jsonb`),
  isPaid: boolean("is_paid").notNull().default(false),
  priceCents: integer("price_cents"),
  currency: text("currency").notNull().default("USD"),
  providerProductId: text("provider_product_id"),
  /** Revealed to buyers only; never rendered on the static page. */
  deliveryNote: text("delivery_note"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  publishedAt: timestamp("published_at", { withTimezone: true }),
});

/**
 * One row per checkout attempt. `reference` is generated by us and travels with
 * the checkout metadata, so a webhook can find the row even when the provider
 * assigns its own order id. `providerOrderId` is filled in from the event.
 */
export const purchases = pgTable(
  "purchases",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    reference: text("reference").notNull(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    projectId: uuid("project_id")
      .notNull()
      .references(() => projects.id, { onDelete: "cascade" }),
    provider: text("provider").notNull(),
    providerOrderId: text("provider_order_id"),
    status: purchaseStatus("status").notNull().default("pending"),
    amountCents: integer("amount_cents").notNull(),
    currency: text("currency").notNull().default("USD"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("purchases_reference_idx").on(table.reference),
    uniqueIndex("purchases_provider_order_idx").on(table.provider, table.providerOrderId),
    index("purchases_user_idx").on(table.userId),
    index("purchases_project_idx").on(table.projectId),
  ],
);

/**
 * Idempotency ledger. A provider may deliver the same event more than once;
 * the unique index turns the second delivery into a no-op instead of a second
 * grant.
 */
export const processedWebhookEvents = pgTable(
  "processed_webhook_events",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    provider: text("provider").notNull(),
    eventId: text("event_id").notNull(),
    type: text("type").notNull(),
    receivedAt: timestamp("received_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("processed_webhook_events_provider_event_idx").on(
      table.provider,
      table.eventId,
    ),
  ],
);

export type UserRecord = typeof users.$inferSelect;
export type ProjectRecord = typeof projects.$inferSelect;
export type NewProject = typeof projects.$inferInsert;
export type PurchaseRecord = typeof purchases.$inferSelect;
export type PurchaseStatus = (typeof purchaseStatus.enumValues)[number];
