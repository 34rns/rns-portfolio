#!/usr/bin/env node
/**
 * Generates the licensing secrets.
 *
 *   node scripts/license-keys.mjs            # print them, change nothing
 *   node scripts/license-keys.mjs --write    # append them to .env.local
 *
 * LICENSE_SECRET is the master key: HKDF expands it into the HMAC key used for
 * lookups and the AES-256-GCM key used for values at rest. Changing it makes
 * every existing order link and license key unreadable, so treat it as
 * permanent and back it up somewhere you would keep a password manager entry.
 *
 * LICENSE_TOKEN_PRIVATE_KEY signs the short-lived tokens the apps verify
 * offline. It is safe to rotate: to do that, move the current value to
 * LICENSE_TOKEN_PRIVATE_KEY_PREVIOUS, run this script again for a new key,
 * deploy, and drop the previous variable after one grace period.
 */
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync } from "node:fs";

const target = ".env.local";

const secret = randomBytes(32).toString("base64url");
const { privateKey, publicKey } = generateKeyPairSync("ed25519");
const privateDer = privateKey.export({ format: "der", type: "pkcs8" }).toString("base64");
const publicDer = publicKey.export({ format: "der", type: "spki" }).toString("base64");

const lines = [
  "# --- Licensing (generated by scripts/license-keys.mjs) ---",
  `LICENSE_SECRET="${secret}"`,
  `LICENSE_TOKEN_PRIVATE_KEY="${privateDer}"`,
  'LICENSE_TOKEN_PRIVATE_KEY_PREVIOUS=""',
  "# Days an app may keep working on a cached token before re-verifying.",
  'LICENSE_GRACE_DAYS="7"',
  "# Hours a freshly issued token stays valid.",
  'LICENSE_TOKEN_TTL_HOURS="12"',
];

const existing = existsSync(target) ? readFileSync(target, "utf8") : "";
const hasSecret = /^LICENSE_SECRET=/m.test(existing);
const write = process.argv.includes("--write");

console.log("\nLicensing secrets\n");
console.log(lines.slice(1).join("\n"));
console.log(`\nPublic key (SPKI, base64) — safe to publish:\n${publicDer}\n`);

if (!write) {
  console.log(`Nothing written. Add these to ${target} and to Vercel, or re-run with --write.\n`);
  process.exit(0);
}

if (hasSecret) {
  console.log(
    `${target} already defines LICENSE_SECRET, so nothing was written.\n` +
      "Rotating that value invalidates every existing order link and license key.\n" +
      "If you really mean to rotate it, remove the old lines first and re-run.\n",
  );
  process.exit(1);
}

const current = existing.endsWith("\n") || existing === "" ? existing : `${existing}\n`;
appendFileSync(target, `${current}${lines.join("\n")}\n`, "utf8");
console.log(`Appended to ${target}. Add the same names in Vercel (Settings → Environment Variables).\n`);
